def native_archive():
    mem=io.BytesIO()
    gcode="""; generated by BambuStudio
M83
G90
G1 X105 Y110 Z0.2
G1 X115 Y110 E0.45
G1 X115 Y120 E0.45
G1 X105 Y120 E0.45
G1 X105 Y110 E0.45
G1 X105 Y110 Z0.4
G1 X120 Y110 E0.5
G1 X120 Y125 E0.5
G1 X105 Y125 E0.5
G1 X105 Y110 E0.5
"""
    with zipfile.ZipFile(mem,"w",zipfile.ZIP_DEFLATED) as z:
        z.writestr("3D/3dmodel.model","<model>test</model>")
        z.writestr("Metadata/plate_1.gcode",gcode)
    return mem.getvalue()


