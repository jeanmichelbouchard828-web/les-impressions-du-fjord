class ReviewTests(unittest.TestCase):
    def test_actual_gcode_in_preview_not_simulated(self):
        data=preview_toolpath(native_archive())
        self.assertEqual(data["layer_count"],2)
        self.assertEqual([round(x["z"],2) for x in data["layers"]],[0.2,0.4])
        self.assertEqual(data["total_moves"],8)
        self.assertEqual(data["source"],"G-code réel du 3MF Bambu Studio")
        self.assertEqual(data["layers"][0]["segments"][0],[105,110,115,110])
        self.assertEqual(data["estimated_seconds"],3600)
        self.assertEqual(data["filament_grams"],20.5)
        self.assertEqual(data["stats_source"],"Bambu Studio (3MF)")

    def test_invalid_toolpaths_are_rejected(self):
        mem=io.BytesIO()
        with zipfile.ZipFile(mem,"w") as z:
            z.writestr("Metadata/plate_1.gcode","G1 X105 Y105\n"*20)
        with self.assertRaisesRegex(SliceReviewError,"Aucune trajectoire"):
            preview_toolpath(mem.getvalue())

    def test_staging_tied_to_session_and_one_time_transfer(self):
        app=Flask("bambu-two-stage")
        app.secret_key="secret-for-test"
        app.config["TESTING"]=True
        register_printer_admin(app,lambda fn:fn,lambda:None,lambda:"",
                               lambda *args,**kw:"ok",db=FakeDb)
        client=app.test_client()
        archive=native_archive()
        with tempfile.TemporaryDirectory() as temp, \
             patch.object(fjord_slice_review,"STAGING_DIRECTORY",Path(temp)), \
             patch("bambu_auto.cli_location",return_value="/usr/local/bin/bambu-studio"), \
             patch("bambu_auto.slice_x2d",return_value=archive) as slicer, \
             patch("fjord_printer._upload") as upload, \
             patch("fjord_printer._status",return_value={"can_start":True,"state":"idle","progress":0,"file":""}) as state:
            prepare=client.post("/admin/atelier-imprimer/preparer",data={
                "stl":(io.BytesIO(b"x"*134),"cube.stl"),"machine":"1","process":"2",
                "filament":"3","material":"PETG","bed_type":"Textured PEI Plate"},
                headers={"Accept":"application/json"},content_type="multipart/form-data")
            self.assertEqual(prepare.status_code,200,prepare.get_data(as_text=True))
            self.assertEqual(prepare.json["preview"]["layer_count"],2)
            self.assertEqual(slicer.call_count,1)
            upload.assert_not_called()
            state.assert_not_called()  # Preview works while printer disconnected.
            token=prepare.json["stage"]
            denied=client.post("/admin/atelier-imprimer/transmettre",
                  data={"stage":"0"*40},headers={"Accept":"application/json"})
            self.assertEqual(denied.status_code,422)
            upload.assert_not_called()
            with client.session_transaction() as s:
                stage=dict(s["fjord_slice_review"])
                stage["at"]-=fjord_slice_review.TTL_SECONDS+1
                s["fjord_slice_review"]=stage
            expired=client.post("/admin/atelier-imprimer/transmettre",
                  data={"stage":token},headers={"Accept":"application/json"})
            self.assertEqual(expired.status_code,422)
            upload.assert_not_called()
            with client.session_transaction() as s:
                import time
                stage=dict(s["fjord_slice_review"])
                stage["at"]=time.time()
                s["fjord_slice_review"]=stage
            # Download retrieves the verified 3MF without uploading or starting it.
            preview_download=client.post("/admin/atelier-imprimer/telecharger-3mf",
                 data={"stage":token},headers={"Accept":"application/octet-stream"})
            self.assertEqual(preview_download.status_code,200)
            self.assertEqual(preview_download.data,archive)
            self.assertIn("attachment",preview_download.headers.get("Content-Disposition",""))
            upload.assert_not_called()
            state.assert_not_called()
            success=client.post("/admin/atelier-imprimer/transmettre",
                  data={"stage":token},headers={"Accept":"application/json"})
            self.assertEqual(success.status_code,200,success.get_data(as_text=True))
            self.assertTrue(success.json["next"].startswith("/admin/atelier-imprimer?"))
            self.assertEqual(upload.call_count,1)
            self.assertEqual(upload.call_args.args[1],archive)
            download=client.post("/admin/atelier-imprimer/telecharger-3mf",
                data={"stage":token},headers={"Accept":"application/octet-stream"})
            # A completed upload consumed this stage, blocking reuse.
            self.assertEqual(download.status_code,422)
            self.assertEqual(upload.call_count,1)

            self.assertTrue(len(success.json["nonce"])>=24)
            self.assertEqual(client.get("/api/admin/atelier/impression-etat").status_code,200)
            # Physical start must require explicit safety checks, a one-use
            # nonce and a matching printer-side file, not a user path.
            nonce=success.json["nonce"]
            with patch("fjord_printer._api",side_effect=lambda path,**kwargs:
                {"Root":[{"Type":"file","VirtualPath":success.json["file"]}]}
                if path=="/files/list" else
                {"VirtualPath":kwargs["payload"]["Path"]} if path=="/start"
                else None) as printer_api:
                started=client.post("/admin/atelier-imprimer/demarrer-atelier",
                    data={"nonce":nonce,"verified":"yes","cleared":"yes","ams":"yes",
                          "path":"gcode/evil.3mf"},headers={"Accept":"application/json"})
                self.assertEqual(started.status_code,200,started.get_data(as_text=True))
                calls=[x for x in printer_api.call_args_list if x.args[0]=="/start"]
                self.assertEqual(len(calls),1)
                self.assertEqual(calls[0].kwargs["payload"]["Path"],success.json["file"])
                self.assertEqual(calls[0].kwargs["payload"]["Plate"],1)
                again=client.post("/admin/atelier-imprimer/demarrer-atelier",
                    data={"nonce":nonce,"verified":"yes","cleared":"yes"})
                self.assertEqual(again.status_code,422)
                self.assertEqual(len([x for x in printer_api.call_args_list if x.args[0]=="/start"]),1)
            second=client.post("/admin/atelier-imprimer/transmettre",
                  data={"stage":token},headers={"Accept":"application/json"})
            self.assertEqual(second.status_code,422)
            self.assertEqual(upload.call_count,1)
            self.assertFalse(list(Path(temp).glob("*.3mf")))


    def test_752_remains_downloadable_and_last_api_error_is_visible_in_diagnostic(self):
        from fjord_printer import PrinterError
        app=Flask("bambu-752-diagnostic")
        app.secret_key="test-diagnostic-key"
        app.config["TESTING"]=True
        register_printer_admin(app,lambda fn:fn,lambda:None,lambda:"",
                               lambda *args,**kw:"ok",db=FakeDb)
        client=app.test_client()
        archive=native_archive()
        def probe(path, **kwargs):
            if path == "/status":
                return {"Features":32,"JobStatus":{"State":"idle","CurrentPrint":{}}}
            if path == "/files/list":
                return {"Root":[]}
            raise AssertionError("Read-only diagnostic may not issue printer commands.")
        safe_error=("Échec du transfert OctoEverywhere (752). Ton 3MF est tranché, "
                    "mais il n'est pas confirmé sur la X2D. "
                    "Le transfert signale un chemin inaccessible ou un refus d'écriture (FTP 550/553).")
        with (
            tempfile.TemporaryDirectory() as temp,
            patch.object(fjord_slice_review,"STAGING_DIRECTORY",Path(temp)),
            patch("bambu_auto.cli_location",return_value="/usr/local/bin/bambu-studio"),
            patch("bambu_auto.slice_x2d",return_value=archive),
            patch("fjord_printer._status",return_value={"can_start":True,"state":"idle","progress":0,"file":""}),
            patch("fjord_printer._upload",side_effect=PrinterError(safe_error)) as upload,
            patch("fjord_printer._api",side_effect=probe) as printer_api,
            patch("fjord_printer._plugin_log_hint",return_value=None),
        ):
            prepare=client.post("/admin/atelier-imprimer/preparer",data={
                "stl":(io.BytesIO(b"x"*134),"cube.stl"),"machine":"1","process":"2",
                "filament":"3","material":"PETG","bed_type":"Textured PEI Plate"},
                headers={"Accept":"application/json"},content_type="multipart/form-data")
            self.assertEqual(prepare.status_code,200)
            stage=prepare.json["stage"]
            failed=client.post("/admin/atelier-imprimer/transmettre",data={"stage":stage},
                               headers={"Accept":"application/json"})
            self.assertEqual(failed.status_code,422)
            self.assertIn("FTP 550/553", failed.json["error"])
            self.assertEqual(upload.call_count,1)
            diagnostic=client.get("/api/admin/atelier/impression-diagnostic")
            self.assertEqual(diagnostic.status_code,200)
            self.assertIn("FTP 550/553", diagnostic.json["last_upload"])
            self.assertNotIn("192.0.2.",str(diagnostic.json))
            downloadable=client.post("/admin/atelier-imprimer/telecharger-3mf",
                                     data={"stage":stage},
                                     headers={"Accept":"application/octet-stream"})
            self.assertEqual(downloadable.status_code,200)
            self.assertEqual(downloadable.data,archive)
            self.assertFalse(any(c.args[0]=="/start" for c in printer_api.call_args_list))


    def test_atelier_start_guard_rejects_busy_unverified_expired_and_wrong_nonce(self):
        import time
        app=Flask("x2d-start-guards")
        app.secret_key="secret-for-guard-tests"
        app.config["TESTING"]=True
        register_printer_admin(app,lambda fn:fn,lambda:None,lambda:"",
                               lambda *args,**kw:"ok")
        client=app.test_client()
        with patch("fjord_printer._api") as printer_api:
            for scenario in ("missing_check","wrong_nonce","expired","busy"):
                with client.session_transaction() as sess:
                    sess["fjord_atelier_start"]={
                        "path":"gcode/fjord_auto_valid.3mf",
                        "nonce":"known-one-time-nonce",
                        "time":time.time()-(1900 if scenario=="expired" else 0)
                    }
                data={"nonce":"known-one-time-nonce","verified":"yes","cleared":"yes"}
                if scenario=="missing_check":data.pop("verified")
                if scenario=="wrong_nonce":data["nonce"]="wrong"
                with patch("fjord_printer._status",return_value={"can_start":False}):
                    response=client.post("/admin/atelier-imprimer/demarrer-atelier",
                                         data=data,headers={"Accept":"application/json"})
                self.assertEqual(response.status_code,422,scenario)
                self.assertFalse(response.json["ok"])
                self.assertEqual(client.post("/admin/atelier-imprimer/demarrer-atelier",
                    data=data).status_code,422)
            printer_api.assert_not_called()


